const STATE_CODES = new Set(US_STATE_OPTIONS.map((s) => s.code))

const STATE_NAME_BY_CODE = new Map(US_STATE_OPTIONS.map((s) => [s.code, s.name]))

/**
 * Parse a feed `state` query value into a 2-letter code.
 * Accepts only known codes (case-insensitive). Empty/absent → null.
 */
export function parseUsStateCode(value: string | null | undefined): string | null {
  if (value == null) return null
  const trimmed = value.trim()
  if (trimmed === '') return null
  const code = trimmed.toUpperCase()
  return STATE_CODES.has(code) ? code : null
}

export function usStateDisplayName(code: string | null | undefined): string | null {
  if (!code) return null
  return STATE_NAME_BY_CODE.get(code.toUpperCase()) ?? null
}
